// ── 티어별 몬스터 필터링 ──

/**
 * 존의 몬스터를 사냥 티어에 따라 필터링
 * - 초급: 하위 1/3 레벨대 (쉬운 몬스터만)
 * - 중급: 하위 2/3 레벨대 (중간까지)
 * - 상급: 전체 레벨대 (모든 몬스터)
 */
export function getMonstersForTier(zone: HuntZone, tier: ZoneTier): Monster[] {
  const [minLv, maxLv] = zone.levelRange;
  const range = maxLv - minLv;

  let cutoff: number;
  if (tier === 'beginner') {
    cutoff = minLv + Math.max(1, Math.ceil(range / 3));
  } else if (tier === 'intermediate') {
    cutoff = minLv + Math.max(1, Math.ceil(range * 2 / 3));
  } else {
    cutoff = maxLv;
  }

  const filtered = zone.monsters.filter(m => m.level <= cutoff);
  return filtered.length > 0 ? filtered : zone.monsters;
}

/** 방 번호(1~5) → 난이도 티어 매핑 */
export function roomToTier(room: number): ZoneTier {
  if (room <= 2) return 'beginner';
  if (room <= 4) return 'intermediate';
  return 'advanced';
}

/** 방 번호 기반 몬스터 필터링 (roomToTier 경유) */
export function getMonstersForRoom(zone: HuntZone, room: number): Monster[] {
  return getMonstersForTier(zone, roomToTier(room));
}

// ── HuntZone 생성 ──

export function generateHuntZones(): HuntZone[] {
  return ALL_ZONE_DEFS.map(def => {
    const [lvMin, lvMax] = def.levelRange;

    // 존 전용 몬스터 풀에서 해당 층 레벨 범위에 맞는 몬스터 선택
    let monsters = getMonstersByIds(def.npcIds)
      .filter(m => m.level >= lvMin && m.level <= lvMax);

    // 해당 범위에 몬스터가 없으면 전체 존 풀 사용
    if (monsters.length === 0) {
      monsters = getMonstersByIds(def.npcIds);
    }

    // 던전 층: 최소 4종 보장 (하위 레벨 필러 — 같은 존 풀에서)
    if (def.zoneType === 'dungeon' && monsters.length < 4) {
      const zonePool = getMonstersByIds(def.npcIds);
      const lower = zonePool
        .filter(m => m.level < lvMin && !monsters.some(b => b.id === m.id))
        .sort((a, b) => b.level - a.level);
      const needed = 4 - monsters.length;
      monsters = [...monsters, ...lower.slice(0, needed)];

      // 존 풀로도 부족하면 글로벌 풀에서 보충
      if (monsters.length < 4) {
        monsters = addLowerFiller(monsters, lvMin, 4);
      }
    }

    // 필드: 최소 3종 보장
    if (def.zoneType === 'field' && monsters.length < 3) {
      monsters = addLowerFiller(monsters, lvMin, 3);
    }

    // 존 난이도 분류
    const zoneTier: ZoneTier =
      def.requiredLevel <= 8  ? 'beginner' :
      def.requiredLevel <= 20 ? 'intermediate' :
                                'advanced';

    return {
      id: def.id,
      name: def.name,
      levelRange: def.levelRange,
      requiredLevel: def.requiredLevel,
      tier: zoneTier,
      monsters,
      dropMaterials: [],
      dropEquipments: [],
      description: `${def.name} — Lv.${lvMin}~${lvMax}`,
      zoneType: def.zoneType,
      dungeonSize: def.dungeonSize,
      floor: def.floor,
      maxFloor: def.maxFloor,
      dungeonGroup: def.dungeonGroup,
    };
  });
}
