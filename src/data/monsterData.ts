// ── 던전 층 생성 ──

interface ZoneDef {
  id: string;
  name: string;
  levelRange: [number, number];
  requiredLevel: number;
  zoneType: 'field' | 'dungeon';
  dungeonSize?: 'small' | 'medium' | 'large';
  floor?: number;
  maxFloor?: number;
  dungeonGroup?: string;
  npcIds: number[];
}

function buildDungeonFloors(src: ZoneSource): ZoneDef[] {
  const [lvMin, lvMax] = src.levelRange;
  const span = lvMax - lvMin;

  let maxFloor: number;
  let dungeonSize: 'small' | 'medium' | 'large';
  if (span <= 8) { maxFloor = 3; dungeonSize = 'small'; }
  else if (span <= 15) { maxFloor = 5; dungeonSize = 'medium'; }
  else { maxFloor = 7; dungeonSize = 'large'; }

  const floorSpan = span / maxFloor;
  return Array.from({ length: maxFloor }, (_, f) => ({
    id: `${src.id}_${f + 1}f`,
    name: `${src.name} ${f + 1}F`,
    levelRange: [
      Math.round(lvMin + floorSpan * f),
      Math.round(lvMin + floorSpan * (f + 1)),
    ] as [number, number],
    requiredLevel: src.requiredLevel,
    zoneType: 'dungeon' as const,
    dungeonSize,
    floor: f + 1,
    maxFloor,
    dungeonGroup: src.id,
    npcIds: src.npcIds,
  }));
}

