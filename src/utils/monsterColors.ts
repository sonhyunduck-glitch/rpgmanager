  '#ffca28', // 9  노랑
  '#8d6e63', // 10 갈색
  '#26a69a', // 11 틸
  '#ff7043', // 12 딥오렌지
  '#7e57c2', // 13 딥퍼플
  '#29b6f6', // 14 라이트블루
  '#d4e157', // 15 라임옐로
  '#f06292', // 16 라이트핑크
